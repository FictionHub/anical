// Stale-page pruning for the generated SEO pages.
//
// The generator names a page after the show's current title: `animeSlug()` is
// "<slug of title>-<AniList id>". Titles change (a translation lands, AniList
// fixes a romanisation), and then tomorrow's run writes a new directory while
// yesterday's stays on disk with its own canonical URL and a sitemap-less life
// of its own. Google ends up with two pages for one show, each claiming to be
// canonical for itself, and whichever ranks is the one with the older data.
//
// The fix is deliberately narrow. A page is only pruned when its show id appears
// twice *and* exactly one of those directories is part of the current build —
// i.e. the slug drifted and we can name the replacement with certainty. The old
// path is then removed and gets a 301 to the new one, so any ranking or inbound
// link moves with it.
//
// Everything else is left alone: a page for a show that has simply dropped out
// of the tracked seasons is stale but not a duplicate, and deleting it would
// turn an indexed URL into a 404. That is a content decision, not this script's.
//
// See scripts/test-seo-prune.mjs for the cases this has to get right.
import { readdir, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";

export const BLOCK_START = "# --- generated: superseded pages (scripts/lib/seo-prune.mjs) ---";
export const BLOCK_END = "# --- end generated ---";

// The AniList id every generated page slug ends with: "kaiju-girl-caramelise-204466".
// A slug without one is not ours to prune, so it returns null instead of a guess.
export function slugId(slug) {
  const m = /-(\d+)$/.exec(String(slug || ""));
  return m ? m[1] : null;
}

// Directory names under site/<group>/ that look like generated pages.
async function pageDirs(root) {
  let entries;
  try {
    entries = await readdir(root, { withFileTypes: true });
  } catch (err) {
    if (err && err.code === "ENOENT") return [];
    throw err;
  }
  return entries.filter(e => e.isDirectory()).map(e => e.name);
}

// Is this a generated page directory (and not, say, a directory someone put
// there by hand)? The generator always writes exactly index.html.
async function isGeneratedPage(root, name) {
  try {
    const inner = await readdir(join(root, name));
    return inner.includes("index.html");
  } catch {
    return false;
  }
}

/**
 * Remove superseded duplicate pages in one group ("anime", "where-to-watch", …)
 * and describe the redirects that should replace them.
 *
 * @param {object} opts
 * @param {string} opts.siteDir     absolute path to site/
 * @param {string} opts.group       directory under site/
 * @param {Set<string>} opts.keep   slugs generated by the current build
 * @param {boolean} [opts.apply]    false = report only, touch nothing (default true)
 * @returns {Promise<{removed: string[], redirects: {from: string, to: string}[], skipped: {id: string, slugs: string[], reason: string}[]}>}
 */
export async function supersedeStalePages({ siteDir, group, keep, apply = true }) {
  const root = join(siteDir, group);
  const removed = [], redirects = [], skipped = [];

  // An empty keep set means the build produced nothing for this group — a failed
  // fetch, not 500 deleted shows. Refuse to prune on that signal.
  if (!keep || !keep.size) return { removed, redirects, skipped };

  const byId = new Map();
  for (const name of await pageDirs(root)) {
    const id = slugId(name);
    if (!id) continue;
    if (!byId.has(id)) byId.set(id, []);
    byId.get(id).push(name);
  }

  for (const [id, names] of byId) {
    if (names.length < 2) continue;
    const live = names.filter(n => keep.has(n));
    if (live.length !== 1) {
      // Zero means the show is no longer built at all (leave both alone); more
      // than one would mean the keep set itself is inconsistent, and guessing
      // wrong here deletes the page Google is currently showing.
      skipped.push({ id, slugs: names, reason: live.length ? "more than one current slug" : "no current slug" });
      continue;
    }
    const keeper = live[0];
    if (!(await isGeneratedPage(root, keeper))) {
      skipped.push({ id, slugs: names, reason: "current page has no index.html" });
      continue;
    }
    for (const name of names) {
      if (name === keeper) continue;
      if (!(await isGeneratedPage(root, name))) {
        skipped.push({ id, slugs: names, reason: `${name} is not a generated page` });
        continue;
      }
      if (apply) await rm(join(root, name), { recursive: true, force: true });
      removed.push(name);
      redirects.push({ from: `/${group}/${name}/`, to: `/${group}/${keeper}/` });
    }
  }

  return { removed, redirects, skipped };
}

/**
 * Run the prune for several groups at once.
 * @param {{siteDir: string, groups: Record<string, Set<string>>, apply?: boolean}} opts
 */
export async function pruneSeoPages({ siteDir, groups, apply = true }) {
  const result = { removed: [], redirects: [], skipped: [] };
  for (const [group, keep] of Object.entries(groups)) {
    const r = await supersedeStalePages({ siteDir, group, keep, apply });
    result.removed.push(...r.removed.map(name => `${group}/${name}`));
    result.redirects.push(...r.redirects);
    result.skipped.push(...r.skipped.map(s => ({ ...s, group })));
  }
  result.redirects.sort((a, b) => a.from.localeCompare(b.from));
  return result;
}

/**
 * Replace (or add, or drop) the managed block in site/_redirects, leaving any
 * hand-written rules untouched. The block goes FIRST because _redirects is
 * first-match-wins: a hand-written catch-all such as `/* /index.html 200` would
 * otherwise swallow every 301 before it was ever considered.
 *
 * Rules are merged with the block already in the file, not replaced by the
 * current run. That detail is the difference between a fix that works and one
 * that works for a week: after the first successful prune the duplicate
 * directory is gone, so the next run finds nothing to prune and would erase the
 * 301 that keeps the old URL alive. A rule is only removed when its source path
 * is live again (`live`, absolute paths) — then the page owns its URL and a
 * redirect would shadow it.
 *
 * @param {string} file
 * @param {{from: string, to: string}[]} redirects  new rules from this run
 * @param {{live?: Set<string>}} [opts]  absolute paths that now exist as pages
 */
export async function writeRedirects(file, redirects, { live } = {}) {
  let existing = "";
  try { existing = await readFile(file, "utf8"); } catch (err) {
    if (!err || err.code !== "ENOENT") throw err;
  }

  const blockRe = new RegExp(`(?:^|\\n)${escapeRe(BLOCK_START)}[\\s\\S]*?${escapeRe(BLOCK_END)}\\n?`, "g");
  const previous = parseBlock(existing);
  const manual = existing.replace(blockRe, "\n").trim();

  const map = new Map(previous.map(r => [r.from, r.to]));
  for (const r of redirects || []) map.set(r.from, r.to);
  if (live) for (const p of live) map.delete(p);

  // Collapse chains (A → B, B → C ⇒ A → C) so a URL is redirected in one hop
  // even after several retitles. Resolved against a snapshot of the map: editing
  // it while walking it would make the result depend on Map iteration order.
  // Rules that only lead back to themselves (a cycle, which a bad pair of prunes
  // could produce) are dropped rather than sent to a 404. Bounded, too, so a
  // pathological chain cannot spin here.
  const collapsed = new Map();
  for (const [from, to] of map) {
    const seen = new Set([from]);
    let target = to, hops = 0;
    while (map.has(target) && hops++ < 10) {
      if (seen.has(target)) break;   // cycle: the rule cannot resolve
      seen.add(target);
      target = map.get(target);
    }
    if (!seen.has(target)) collapsed.set(from, target);
  }

  const lines = [...collapsed.entries()].map(([from, to]) => `${from} ${to} 301`).sort();
  const block = lines.length ? [BLOCK_START, ...lines, BLOCK_END].join("\n") : "";
  const out = [block, manual].filter(Boolean).join("\n\n");

  if (!out) {
    // Nothing generated and nothing hand-written: don't leave an empty file
    // behind (it would be a new tracked file that says nothing).
    await rm(file, { force: true });
    return { written: false, count: 0 };
  }
  await writeFile(file, out + "\n", "utf8");
  return { written: true, count: lines.length };
}

// Rules from the managed block, in file order. Lines are "<from> <to> 301".
function parseBlock(text) {
  const m = new RegExp(`${escapeRe(BLOCK_START)}([\\s\\S]*?)${escapeRe(BLOCK_END)}`).exec(text);
  if (!m) return [];
  return m[1].split("\n").map(line => line.trim()).filter(Boolean).map(line => {
    const [from, to] = line.split(/\s+/);
    return from && to ? { from, to } : null;
  }).filter(Boolean);
}

function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
